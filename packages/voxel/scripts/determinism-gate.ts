/**
 * Determinism gate: regenerates the canonical starter artifact from the
 * committed seed and proves it is byte-identical to what is on disk. Any
 * generator change that alters output fails the build. Run:
 * bun packages/voxel/scripts/determinism-gate.ts
 */
import { readFileSync } from "node:fs"
import {
  buildDrake,
  DRAKE_GRID,
  drakeTemplate,
  exportGlb,
  type GlbManifest,
  meshGrid,
  sampleDna,
  VOXEL_SIZE,
  voxelize,
} from "@apex/voxel"

const SEED = 42
const GLB_PATH = `artifacts/drake-${SEED}.glb`
const MANIFEST_PATH = `artifacts/drake-${SEED}.manifest.json`

const dna = sampleDna(drakeTemplate, SEED)
const build = buildDrake(dna)
const meshes = meshGrid(voxelize(build.fields, DRAKE_GRID))
const { glb, manifest } = exportGlb({
  archetype: "draconic",
  seed: SEED,
  dnaJson: JSON.stringify(dna),
  voxelSize: VOXEL_SIZE,
  colors: build.colors,
  pivots: build.pivots,
  parts: meshes,
})

const fail = (why: string): never => {
  console.error(`DETERMINISM GATE FAILED: ${why}`)
  process.exit(1)
}

const committedManifest = JSON.parse(
  readFileSync(MANIFEST_PATH, "utf8"),
) as GlbManifest
// Deep-compare the full manifest: any field drift (hashes, triCount, pivots,
// generator version) means the committed artifact no longer matches output.
if (JSON.stringify(manifest) !== JSON.stringify(committedManifest)) {
  fail(
    `manifest mismatch\n  committed:   ${JSON.stringify(committedManifest)}\n  regenerated: ${JSON.stringify(manifest)}`,
  )
}
const committedGlb = readFileSync(GLB_PATH)
if (!Buffer.from(glb).equals(committedGlb)) {
  fail(`${GLB_PATH} differs from regenerated output`)
}
console.log(
  `determinism gate OK: seed ${SEED} regenerated byte-identical (${glb.byteLength} bytes, tris ${manifest.triCount})`,
)
