/**
 * Determinism gate: regenerates the canonical starter artifacts for EVERY
 * registered archetype from the committed seed and proves they are
 * byte-identical to what is on disk — for every life stage with committed
 * artifacts (baby keeps the bare filename, other stages are suffixed).
 * Any generator change that alters output fails the build.
 * Run: bun packages/voxel/scripts/determinism-gate.ts
 */
import { readFileSync } from "node:fs"
import {
  archetypes,
  exportGlb,
  type GlbManifest,
  generate,
  generateProp,
  meshGrid,
  type PropGenerated,
  props,
  VOXEL_SIZE,
  voxelize,
} from "@apex/voxel"

const SEED = 42

/** Life stages with committed GLB artifacts; baby keeps the bare filename. */
const GATED_STAGES = ["baby", "juvenile", "champion"] as const

const fail = (why: string): never => {
  console.error(`DETERMINISM GATE FAILED: ${why}`)
  process.exit(1)
}

/** Props: regenerate from the seed and hash into one committed manifest. */
const PROP_MANIFEST = "artifacts/props-42.json"

function propDigest({ id, dna, build, def }: PropGenerated & { id: string }): {
  sha256: string
  tris: number
} {
  const grid = voxelize(build.fields, def.grid)
  const meshes = meshGrid(grid)
  const canonical = JSON.stringify({
    id,
    dna,
    colors: build.colors,
    meshes,
  })
  const sha256 = new Bun.CryptoHasher("sha256").update(canonical).digest("hex")
  return { sha256, tris: meshes.reduce((n, m) => n + m.indices.length / 3, 0) }
}

for (const [id, def] of Object.entries(archetypes)) {
  for (const stage of GATED_STAGES) {
    const suffix = stage === "baby" ? "" : `-${stage}`
    const glbPath = `artifacts/${id}-${SEED}${suffix}.glb`
    const manifestPath = `artifacts/${id}-${SEED}${suffix}.manifest.json`

    const { dna, build } = generate(id, SEED, stage)
    const meshes = meshGrid(voxelize(build.fields, def.grid))
    const { glb, manifest } = exportGlb({
      archetype: def.id,
      seed: SEED,
      dnaJson: JSON.stringify(dna),
      voxelSize: VOXEL_SIZE,
      colors: build.colors,
      pivots: build.pivots,
      parts: meshes,
    })

    let committedManifest: GlbManifest
    try {
      committedManifest = JSON.parse(
        readFileSync(manifestPath, "utf8"),
      ) as GlbManifest
    } catch {
      fail(
        `${manifestPath} is missing or unparseable - run export-artifact.ts to (re)commit it`,
      )
    }
    // Deep-compare the full manifest: any field drift (hashes, triCount,
    // pivots, generator version) means the committed artifact no longer
    // matches output.
    if (JSON.stringify(manifest) !== JSON.stringify(committedManifest)) {
      fail(
        `manifest mismatch for ${id} ${stage}\n  committed:   ${JSON.stringify(committedManifest)}\n  regenerated: ${JSON.stringify(manifest)}`,
      )
    }

    let committedGlb: Buffer
    try {
      committedGlb = readFileSync(glbPath)
    } catch {
      fail(`${glbPath} is missing - run export-artifact.ts to (re)commit it`)
    }
    if (!Buffer.from(glb).equals(committedGlb)) {
      fail(`${glbPath} differs from regenerated output`)
    }

    console.log(
      `determinism gate OK: ${id} seed ${SEED} ${stage} regenerated byte-identical (${glb.byteLength} bytes, tris ${manifest.triCount})`,
    )
  }
}

// Props share the pipeline but produce no GLB artifacts — they are hashed
// instead. `--write` (re)commits the manifest; the standard run compares.
const generated = Object.entries(props).map(([id]) => ({
  ...generateProp(id, SEED),
  id,
}))
const digests = Object.fromEntries(generated.map((g) => [g.id, propDigest(g)]))

if (process.argv.includes("--write")) {
  await Bun.write(PROP_MANIFEST, `${JSON.stringify(digests, null, 2)}\n`)
  console.log(`determinism gate: prop manifest committed to ${PROP_MANIFEST}`)
} else {
  let committed: Record<string, { sha256: string; tris: number }>
  try {
    committed = JSON.parse(
      readFileSync(PROP_MANIFEST, "utf8"),
    ) as typeof digests
  } catch {
    fail(
      `${PROP_MANIFEST} is missing or unparseable - run the gate with --write to (re)commit it`,
    )
  }
  for (const id of Object.keys(props)) {
    if (committed[id] === undefined) {
      fail(`prop manifest ${PROP_MANIFEST} has no entry for "${id}"`)
    }
    if (committed[id].sha256 !== digests[id].sha256) {
      fail(`prop digest mismatch for ${id} seed ${SEED}`)
    }
  }
  const tris = Object.entries(digests)
    .map(([id, d]) => `${id} tris ${d.tris}`)
    .join(", ")
  console.log(
    `determinism gate OK: ${Object.keys(props).length} props seed ${SEED} regeneration digests match (${tris})`,
  )
}
