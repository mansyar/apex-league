/**
 * Determinism gate: regenerates the canonical starter artifact for EVERY
 * registered archetype from the committed seed and proves it is byte-identical
 * to what is on disk. Any generator change that alters output fails the build.
 * Run: bun packages/voxel/scripts/determinism-gate.ts
 */
import { readFileSync } from "node:fs"
import {
  archetypes,
  exportGlb,
  type GlbManifest,
  generate,
  meshGrid,
  VOXEL_SIZE,
  voxelize,
} from "@apex/voxel"

const SEED = 42

const fail = (why: string): never => {
  console.error(`DETERMINISM GATE FAILED: ${why}`)
  process.exit(1)
}

for (const [id, def] of Object.entries(archetypes)) {
  const glbPath = `artifacts/${id}-${SEED}.glb`
  const manifestPath = `artifacts/${id}-${SEED}.manifest.json`

  const { dna, build } = generate(id, SEED)
  const meshes = meshGrid(voxelize(build.fields, def.grid))
  const { glb, manifest } = exportGlb({
    archetype: def.id,
    seed: SEED,
    dnaJson: JSON.stringify(dna),
    voxelSize: VOXEL_SIZE,
    colors: build.colors,
    pivots: build.pivots,
    parts: meshes,
  })

  let committedManifest: GlbManifest
  try {
    committedManifest = JSON.parse(
      readFileSync(manifestPath, "utf8"),
    ) as GlbManifest
  } catch {
    fail(
      `${manifestPath} is missing or unparseable - run export-artifact.ts to (re)commit it`,
    )
  }
  // Deep-compare the full manifest: any field drift (hashes, triCount, pivots,
  // generator version) means the committed artifact no longer matches output.
  if (JSON.stringify(manifest) !== JSON.stringify(committedManifest)) {
    fail(
      `manifest mismatch for ${id}\n  committed:   ${JSON.stringify(committedManifest)}\n  regenerated: ${JSON.stringify(manifest)}`,
    )
  }

  let committedGlb: Buffer
  try {
    committedGlb = readFileSync(glbPath)
  } catch {
    fail(`${glbPath} is missing - run export-artifact.ts to (re)commit it`)
  }
  if (!Buffer.from(glb).equals(committedGlb)) {
    fail(`${glbPath} differs from regenerated output`)
  }

  console.log(
    `determinism gate OK: ${id} seed ${SEED} regenerated byte-identical (${glb.byteLength} bytes, tris ${manifest.triCount})`,
  )
}
